def get_suggestions(phonetic_input):
    """
    Get Bengali suggestions for phonetic input

    Args:
        phonetic_input (str): Phonetic Latin input

    Returns:
        list: List of Bengali word suggestions
    """
    if not phonetic_input:
        return []

    lower_input = phonetic_input.lower()
    suggestions = []

    # Exact match
    if lower_input in DICTIONARY:
        suggestions.extend(DICTIONARY[lower_input])

    # Prefix match (autocomplete)
    for key, words in DICTIONARY.items():
        if key.startswith(lower_input) and key != lower_input:
            suggestions.extend(words)
            if len(suggestions) >= 9:  # Limit autocomplete
                break

    return suggestions[:9]  # Return top 9

